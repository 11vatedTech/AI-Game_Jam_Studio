"""Synthesise the EMBERKEEP sound identity from first principles.

No sample libraries, no third-party IP: every sound here is generated by code and is therefore
unambiguously licensable. Outputs 44.1 kHz mono WAV, then the caller encodes to Ogg Vorbis.

Design (art bible §10): 60 BPM, minor mode, sparse; warmth is low-frequency, cold is airy noise.
"""

from __future__ import annotations

import argparse
import math
import random
import sys
import wave
from pathlib import Path

RATE = 44100


def write_wav(path: Path, samples: list[float], peak: float = 0.86) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    top = max((abs(s) for s in samples), default=1.0) or 1.0
    scale = peak / top
    frames = bytearray()
    for s in samples:
        # Soft clip keeps transients from sounding digital.
        value = math.tanh(s * scale * 1.15) * 0.92
        frames += int(max(-1.0, min(1.0, value)) * 32767).to_bytes(2, "little", signed=True)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(RATE)
        handle.writeframes(bytes(frames))


def one_pole_lowpass(signal: list[float], cutoff: float) -> list[float]:
    alpha = 1.0 - math.exp(-2.0 * math.pi * cutoff / RATE)
    out, state = [], 0.0
    for value in signal:
        state += alpha * (value - state)
        out.append(state)
    return out


def ambience(duration: float = 48.0) -> list[float]:
    """Cold water, wind through stone, and a low sustained minor drone."""
    random.seed(17)
    total = int(duration * RATE)
    noise = [random.uniform(-1.0, 1.0) for _ in range(total)]
    air = one_pole_lowpass(noise, 620.0)
    wind = one_pole_lowpass(noise, 180.0)
    partials = [(55.0, 0.30), (82.5, 0.17), (110.0, 0.13), (164.8, 0.07), (220.0, 0.035)]
    out: list[float] = []
    for i in range(total):
        t = i / RATE
        drone = 0.0
        for freq, amp in partials:
            lfo = 0.72 + 0.28 * math.sin(2.0 * math.pi * (0.021 * freq / 55.0) * t + freq)
            drone += amp * lfo * math.sin(2.0 * math.pi * freq * t)
        air_mod = 0.5 + 0.5 * math.sin(2.0 * math.pi * 0.037 * t)
        wind_mod = 0.4 + 0.6 * math.sin(2.0 * math.pi * 0.013 * t + 1.7)
        # Distant water: a slow amplitude-modulated band of noise.
        water = air[i] * 0.16 * air_mod + wind[i] * 0.34 * wind_mod
        out.append(drone * 0.55 + water)
    # Loop-safe crossfade at both ends.
    fade = int(2.0 * RATE)
    for i in range(fade):
        gain = i / fade
        out[i] *= gain
        out[-1 - i] *= gain
    return out


def ignite(duration: float = 2.4) -> list[float]:
    """A warm swell: sub thump, airy whoosh, rising harmonic, ember crackle."""
    random.seed(5)
    total = int(duration * RATE)
    out = []
    for i in range(total):
        t = i / RATE
        env = math.exp(-t * 1.6) * min(1.0, t / 0.05)
        swell = math.exp(-((t - 0.22) ** 2) / 0.06)
        sweep = 130.0 + 300.0 * (1.0 - math.exp(-t * 3.2))
        body = math.sin(2.0 * math.pi * sweep * t) * swell * 0.6
        sub = math.sin(2.0 * math.pi * 52.0 * t) * env * 0.9
        whoosh = random.uniform(-1.0, 1.0) * swell * 0.45
        crackle = (random.uniform(-1.0, 1.0) if random.random() < 0.004 else 0.0) * math.exp(-t * 2.2)
        out.append(body + sub + whoosh + crackle * 0.6)
    return one_pole_lowpass(out, 5200.0)


def chime(duration: float = 1.6) -> list[float]:
    """A single struck-glass note (FM bell), the sound of remembering."""
    total = int(duration * RATE)
    base = 880.0
    out = []
    for i in range(total):
        t = i / RATE
        env = math.exp(-t * 2.6)
        modulator = math.sin(2.0 * math.pi * base * 2.01 * t) * 2.4 * math.exp(-t * 4.0)
        tone = math.sin(2.0 * math.pi * base * t + modulator)
        shimmer = math.sin(2.0 * math.pi * base * 3.98 * t) * 0.22 * math.exp(-t * 6.0)
        out.append((tone * 0.8 + shimmer) * env)
    return out


def dawn(duration: float = 6.0) -> list[float]:
    """Resolution: a minor triad opening to its relative major, slow attack."""
    total = int(duration * RATE)
    chord_a = [110.0, 130.81, 164.81, 220.0]
    chord_b = [110.0, 138.59, 164.81, 277.18]
    out = []
    for i in range(total):
        t = i / RATE
        attack = min(1.0, t / 1.4)
        mix = max(0.0, min(1.0, (t - 1.8) / 2.6))
        release = 1.0 if t < duration - 1.6 else max(0.0, (duration - t) / 1.6)
        value = 0.0
        for index, freq in enumerate(chord_a):
            amp = 0.24 / (1.0 + index * 0.35)
            value += amp * math.sin(2.0 * math.pi * freq * t) * (1.0 - mix)
        for index, freq in enumerate(chord_b):
            amp = 0.24 / (1.0 + index * 0.3)
            value += amp * math.sin(2.0 * math.pi * freq * t) * mix
        out.append(value * attack * release)
    return one_pole_lowpass(out, 4200.0)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", required=True, type=Path)
    args = parser.parse_args()
    out_dir: Path = args.out_dir
    jobs = {
        "ambience": ambience(),
        "ignite": ignite(),
        "chime": chime(),
        "dawn": dawn(),
    }
    report = {}
    for name, samples in jobs.items():
        path = out_dir / f"{name}.wav"
        write_wav(path, samples)
        report[name] = {"path": str(path), "seconds": round(len(samples) / RATE, 2),
                        "samples": len(samples)}
        print(f"WROTE {path} ({report[name]['seconds']}s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
